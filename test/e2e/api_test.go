func TestE2E_RedirectURL(t *testing.T) {
	setupE2E(t)
	defer teardownE2E(t)

	customCode := "rdr" + time.Now().Format("0405")
	expectedURL := "https://www.redirect-test.com"

	// Create URL first
	ctx := context.Background()
	_, err := testURLStore.Create(ctx, expectedURL, customCode)
	if err != nil {
		t.Fatalf("Failed to create test URL: %v", err)
	}

	// Test redirect
	req := httptest.NewRequest(http.MethodGet, "/"+customCode, nil)
	w := httptest.NewRecorder()

	testRouter.ServeHTTP(w, req)

	if w.Code != http.StatusFound {
		t.Errorf("Expected status 302, got %d", w.Code)
	}

	location := w.Header().Get("Location")
	if location != expectedURL {
		t.Errorf("Expected redirect to '%s', got '%s'", expectedURL, location)
	}

	// Verify access count incremented (give async operation time to complete)
	time.Sleep(100 * time.Millisecond)
	urlRecord, _ := testURLStore.GetByShortCode(ctx, customCode)
	if urlRecord.AccessCount < 1 {
		t.Errorf("Expected access_count >= 1, got %d", urlRecord.AccessCount)
	}

	// Cleanup
	defer func() {
		testURLStore.Delete(ctx, customCode)
	}()
}

