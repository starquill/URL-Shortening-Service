func TestE2E_CacheInvalidation(t *testing.T) {
	setupE2E(t)
	defer teardownE2E(t)

	customCode := "cch" + time.Now().Format("0405")
	originalURL := "https://www.cache-original.com"
	newURL := "https://www.cache-updated.com"

	ctx := context.Background()

	// Create URL
	_, err := testURLStore.Create(ctx, originalURL, customCode)
	if err != nil {
		t.Fatalf("Failed to create test URL: %v", err)
	}

	// Populate cache via redirect
	req1 := httptest.NewRequest(http.MethodGet, "/"+customCode, nil)
	w1 := httptest.NewRecorder()
	testRouter.ServeHTTP(w1, req1)

	// Verify cache has original URL
	cachedURL, err := testCache.Get(ctx, customCode)
	if err != nil || cachedURL != originalURL {
		t.Errorf("Expected cache to have '%s', got '%s' (error: %v)", originalURL, cachedURL, err)
	}

	// Update URL (should invalidate cache)
	payload := map[string]string{"url": newURL}
	body, _ := json.Marshal(payload)
	req2 := httptest.NewRequest(http.MethodPut, "/api/urls/"+customCode, bytes.NewReader(body))
	req2.Header.Set("Content-Type", "application/json")
	w2 := httptest.NewRecorder()
	testRouter.ServeHTTP(w2, req2)

	// Verify cache was invalidated
	_, err = testCache.Get(ctx, customCode)
	if err == nil {
		t.Error("Expected cache to be invalidated after update")
	}

	// Redirect again (should populate cache with new URL)
	req3 := httptest.NewRequest(http.MethodGet, "/"+customCode, nil)
	w3 := httptest.NewRecorder()
	testRouter.ServeHTTP(w3, req3)

	// Verify redirect goes to new URL
	location := w3.Header().Get("Location")
	if location != newURL {
		t.Errorf("Expected redirect to '%s', got '%s'", newURL, location)
	}

	// Cleanup
	defer func() {
		testURLStore.Delete(ctx, customCode)
	}()
}
